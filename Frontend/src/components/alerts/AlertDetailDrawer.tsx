import type { AlertRecord } from '../../types'
import './AlertDetailDrawer.css'

interface Props {
  alert: AlertRecord
  onClose: () => void
}

export const AlertDetailDrawer = ({
  alert,
  onClose,
}: Props) => {

  // Image URL from backend API - UNCHANGED
  const imageUrl = alert.picture
    ? `http://localhost:8080/api/alerts/${alert.id}/image`
    : null

  // Check if incident is WARNING or DANGER
  const isWarning =
    alert.incidentType?.toUpperCase() === 'WARNING'

  return (
    <div
      className="drawer-overlay"
      onClick={onClose}
    >
      <div
        className="drawer"
        onClick={(event) =>
          event.stopPropagation()
        }
      >

        <div className="drawer__header">
          <div>
            <h3>Alert Details</h3>

            <span>
              {isWarning
                ? 'WARNING INCIDENT'
                : 'DANGER INCIDENT'}
            </span>
          </div>

          <button
            type="button"
            onClick={onClose}
          >
            Close
          </button>
        </div>

        <div className="drawer__content">

          {/* Alert ID - from database */}
          <div className="detail-row">
            <span>Alert ID</span>
            <strong>
              {alert.id}
            </strong>
          </div>

          {/* Event ID - generated by backend */}
          <div className="detail-row">
            <span>Event ID</span>
            <strong>
              {alert.eventId ?? 'Unknown'}
            </strong>
          </div>

          {/* ✅ CHANGED: Incident Type - from JSON incident_type */}
          <div className="detail-row">
            <span>Incident Type</span>
            <strong>
              {alert.incidentType ?? 'Unknown'}
            </strong>
          </div>

          {/* ✅ CHANGED: Person - from JSON person_id */}
          <div className="detail-row">
            <span>Person</span>
            <strong>
              {alert.personId ?? 'Unknown'}
            </strong>
          </div>

          {/* Camera ID - from request parameter */}
          <div className="detail-row">
            <span>Camera ID</span>
            <strong>
              {alert.cameraId ?? 'Unknown'}
            </strong>
          </div>

          {/* ✅ CHANGED: Severity - same as incidentType */}
          <div className="detail-row">
            <span>Severity</span>
            <strong>
              {alert.incidentType ?? 'Unknown'}
            </strong>
          </div>

          {/* Status - always ACTIVE */}
          <div className="detail-row">
            <span>Status</span>
            <strong>
              {alert.status ?? 'Unknown'}
            </strong>
          </div>

          {/* ✅ CHANGED: Zone - from JSON zone_name */}
          <div className="detail-row">
            <span>Zone</span>
            <strong>
              {alert.zoneName ?? 'Unknown'}
            </strong>
          </div>

          {/* Timestamp - from JSON */}
          <div className="detail-row">
            <span>Timestamp</span>
            <strong>
              {alert.timestamp
                ? new Date(
                    alert.timestamp
                  ).toLocaleString()
                : 'Unknown'}
            </strong>
          </div>

          {/* Dwell Time - from JSON dwell_seconds */}
          <div className="detail-row">
            <span>Dwell Time</span>
            <strong>
              {alert.dwellSeconds != null
                ? `${alert.dwellSeconds} sec`
                : 'Not applicable'}
            </strong>
          </div>

          {/* Picture - UNCHANGED */}
          {imageUrl ? (
            <div className="alert-image">
              <span>Incident Picture</span>

              <img
                src={imageUrl}
                alt="Safety incident"
              />
            </div>
          ) : (
            <div className="detail-row">
              <span>Incident Picture</span>
              <strong>
                Not available
              </strong>
            </div>
          )}

        </div>
      </div>
    </div>
  )
}